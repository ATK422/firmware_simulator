#!/usr/bin/env python3
"""Makes the nereus packs for running nereus with firmware_simulator's emulated boards in the loop.

    python3 integrations/nereus/make_packs.py NEREUS_DIR OUT_DIR [--pool robosub|rpac] [--actuators firmware|nereus]
        [--depth firmware|nereus] [--real-time-factor 0.5]

From the uwrt_talos bridge pack and a Talos scenario of your nereus checkout (nereus is not ours to change, so the
variant is derived from whatever version you have) it writes

* OUT_DIR/bridges/uwrt_talos_firmware/bridge.yaml: the bridge with the firmware in the loop
  ([`firmware_bridge_pack`]): nereus's thrusters take the thrust the emulated ESC boards make
  (simulator/firmware_thruster_forces, from firmware_bridge.py) instead of the controller's thruster_forces;
  nereus's kill follows the PoAC firmware's state/kill; and the streams the firmware now publishes itself (ESC
  telemetry, the kill state, depth through riptide's depth_converter, actuator status) are switched off or moved
  under simulator/ so nothing has two publishers;
* OUT_DIR/scenarios/talos_firmware_POOL/scenario.yaml: the scenario with that bridge, its other packs pointed at
  your nereus checkout, and thruster lag switched off (the emulated ESCs and motors are the lag now).

Then `ros2 launch nereus sim.launch.py scenario:=OUT_DIR/scenarios/talos_firmware_POOL` (scripts/nereus_firmware_sim.sh
does all of it). integrations/nereus/packs/ has the bridge as generated from nereus 58763df, for reference.
"""

from __future__ import annotations

import argparse
import copy
import os
import sys
from pathlib import Path

FORCES_TOPIC = "simulator/firmware_thruster_forces"
SCENARIOS = {"robosub": "talos_uwrt", "rpac": "talos_uwrt_rpac"}
PACK_ROLES = ("robot", "pool", "tasks", "bridge", "equipment")
# Streams of nereus's that the firmware takes over, by what they publish
TELEMETRY_TOPIC = "state/thrusters/telemetry"
DEPTH_TOPIC = "depth/pose"
ACTUATOR_TOPICS = ("state/actuator/status", "state/actuator/busy", "state/actuator/cmd_status")


class PackError(ValueError):
    pass


def _stream(pack: dict, sid: str) -> dict:
    for s in pack.get("streams", []):
        if s.get("id") == sid:
            return s
    raise PackError(f"the bridge pack has no stream {sid!r} (nereus changed? update make_packs.py)")


def firmware_bridge_pack(
    upstream: dict,
    *,
    depth: str = "firmware",
    actuators: str = "firmware",
    real_time_factor: float | None = None,
    forces_topic: str = FORCES_TOPIC,
) -> dict:
    """The firmware-in-the-loop variant of nereus's uwrt_talos bridge pack (a parsed bridge.yaml)."""
    if depth not in ("firmware", "nereus") or actuators not in ("firmware", "nereus"):
        raise PackError("depth and actuators are 'firmware' or 'nereus'")
    pack = copy.deepcopy(upstream)
    pack["id"] = f"{upstream.get('id', 'uwrt_talos')}_firmware"
    pack["description"] = (
        f"{upstream.get('description', '').rstrip('.')}; with firmware_simulator's emulated boards in the loop "
        "(generated by firmware_simulator's integrations/nereus/make_packs.py)."
    )
    kill = pack.get("kill") or {}
    command, state = kill.get("command_stream"), kill.get("state_stream")
    if not command or not state:
        raise PackError("the bridge pack has no kill streams")

    # The thrusters take what the emulated ESC boards push, in the controller's order (thrusters.order is unchanged)
    forces = next(
        (s for s in pack["streams"] if s.get("native") == "command:thrusters.set_forces"),
        None,
    )
    if forces is None:
        raise PackError("the bridge pack has no command:thrusters.set_forces stream")
    forces["topic"] = forces_topic

    # The kill switch is the PoAC firmware's: its state/kill (std_msgs/Bool, published reliable by the C firmware
    # and best effort by titan_bridge, so subscribe best effort) kills and unkills nereus too
    sw = _stream(pack, command)
    sw["topic"] = "state/kill"
    sw["message_type"] = "std_msgs/msg/Bool"
    sw.pop("accept_if", None)
    sw["fields"] = {"killed": {"from": "data"}}
    sw["qos"] = dict(sw.get("qos", {}), reliability="best_effort")
    # ... and nereus's own kill state moves out of the way
    _stream(pack, state)["topic"] = "simulator/kill_state"

    def publishes(s, topic):
        return s.get("direction") == "publish" and s.get("topic") == topic

    drop = {TELEMETRY_TOPIC}
    if depth == "firmware":
        drop.add(DEPTH_TOPIC)
    pack["streams"] = [s for s in pack["streams"] if not any(publishes(s, t) for t in drop)]
    if actuators == "firmware":
        for s in pack["streams"]:
            if any(publishes(s, t) for t in ACTUATOR_TOPICS):
                s["topic"] = "simulator/nereus/" + s["topic"]
    if real_time_factor is not None:
        pack.setdefault("clock", {})["real_time_factor"] = float(real_time_factor)
    check_firmware_pack(pack, depth=depth, actuators=actuators)
    return pack


def check_firmware_pack(pack: dict, *, depth: str = "firmware", actuators: str = "firmware") -> None:
    """Raises PackError unless `pack` is a firmware-in-the-loop bridge: no stream publishes what the firmware
    does, the thrusters listen to the firmware's thrust, and the kill follows state/kill."""
    published = [s["topic"] for s in pack["streams"] if s.get("direction") == "publish"]
    taken = [TELEMETRY_TOPIC, "state/kill"]
    if depth == "firmware":
        taken.append(DEPTH_TOPIC)
    if actuators == "firmware":
        taken += ACTUATOR_TOPICS
    for t in taken:
        if t in published:
            raise PackError(f"the bridge still publishes {t}, which the firmware publishes")
    forces = [s for s in pack["streams"] if s.get("native") == "command:thrusters.set_forces"]
    if len(forces) != 1 or forces[0]["topic"] != FORCES_TOPIC:
        raise PackError(f"the thrusters must take {FORCES_TOPIC}")
    kill = _stream(pack, pack["kill"]["command_stream"])
    if kill["topic"] != "state/kill" or kill["message_type"] != "std_msgs/msg/Bool":
        raise PackError("the kill must follow the firmware's state/kill")
    if len(pack["thrusters"]["order"]) != 8:
        raise PackError("Talos has eight thrusters")


def _relative(target: Path, start: Path) -> str:
    # nereus takes pack paths relative to the scenario folder only
    return Path(os.path.relpath(target.resolve(), start.resolve())).as_posix()


def firmware_scenario(upstream: dict, upstream_dir: Path, bridge_dir: Path, pool: str, scenario_dir: Path) -> dict:
    """The scenario (to be written to `scenario_dir`) with the firmware bridge pack, its other packs those of the
    nereus checkout (relative paths, as nereus wants them), and thruster lag off: the emulated ESC boards' motor
    models already lag, and nereus would add its own on top."""
    sc = copy.deepcopy(upstream)
    for role in PACK_ROLES:
        if role in sc:
            sc[role] = _relative(upstream_dir / sc[role], scenario_dir)
    sc["bridge"] = _relative(bridge_dir, scenario_dir)
    sc["id"] = f"{upstream.get('id', 'talos')}_firmware"
    sc["description"] = f"{upstream.get('description', '').rstrip('.')}; firmware_simulator's boards in the loop ({pool})."
    sc["thruster_overrides"] = list(sc.get("thruster_overrides", [])) + [
        {
            "parameters": {
                "delay_s": 0.0,
                "rise_time_s": 0.0,
                "fall_time_s": 0.0,
                "slew_rate_n_s": 0.0,
                "forward_limit_n": 60.0,
                "reverse_limit_n": 60.0,
                "deadband_n": 0.0,
            }
        }
    ]
    return sc


HEADER = """# Generated by firmware_simulator's integrations/nereus/make_packs.py from {source}.
# Do not edit: run it again (scripts/nereus_firmware_sim.sh does) after updating nereus.
"""


def write(nereus: Path, out: Path, pool="robosub", depth="firmware", actuators="firmware", real_time_factor=None):
    """Writes both packs; returns the scenario folder."""
    import yaml

    packs = nereus / "content" / "packs"
    upstream_bridge = packs / "bridges" / "uwrt_talos" / "bridge.yaml"
    if pool not in SCENARIOS:
        raise PackError(f"unknown pool {pool!r} (known: {', '.join(SCENARIOS)})")
    upstream_scenario = packs / "scenarios" / SCENARIOS[pool] / "scenario.yaml"
    for f in (upstream_bridge, upstream_scenario):
        if not f.exists():
            raise PackError(f"{f} not found: is {nereus} a nereus checkout?")
    bridge = firmware_bridge_pack(
        yaml.safe_load(upstream_bridge.read_text()),
        depth=depth,
        actuators=actuators,
        real_time_factor=real_time_factor,
    )
    bridge_dir = out / "bridges" / bridge["id"]
    bridge_dir.mkdir(parents=True, exist_ok=True)
    (bridge_dir / "bridge.yaml").write_text(
        HEADER.format(source=upstream_bridge) + yaml.safe_dump(bridge, sort_keys=False, width=120)
    )
    scenario_dir = out / "scenarios" / f"talos_firmware_{pool}"
    scenario_dir.mkdir(parents=True, exist_ok=True)
    scenario = firmware_scenario(
        yaml.safe_load(upstream_scenario.read_text()), upstream_scenario.parent, bridge_dir, pool, scenario_dir
    )
    (scenario_dir / "scenario.yaml").write_text(
        HEADER.format(source=upstream_scenario) + yaml.safe_dump(scenario, sort_keys=False, width=120)
    )
    return scenario_dir


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("nereus", type=Path, help="your nereus checkout")
    p.add_argument("out", type=Path, help="where the packs go")
    p.add_argument("--pool", default="robosub", choices=sorted(SCENARIOS))
    p.add_argument("--depth", default="firmware", choices=["firmware", "nereus"], help="who publishes depth/pose")
    p.add_argument("--actuators", default="firmware", choices=["firmware", "nereus"], help="who publishes state/actuator/*")
    p.add_argument("--real-time-factor", type=float, help="nereus's starting real_time_factor")
    a = p.parse_args(argv)
    try:
        print(write(a.nereus, a.out, a.pool, a.depth, a.actuators, a.real_time_factor))
    except (PackError, OSError) as e:
        print(f"make_packs.py: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
