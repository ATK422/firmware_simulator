#!/usr/bin/env python3
"""Generates boards/<dir>/<board>.toml from titan_firmware's board headers.

    python3 scripts/gen_boards.py            # writes boards/
    python3 scripts/gen_boards.py --check    # fails if boards/ is out of date

Each header (lib/titan_boards/include/boards/**/*.h, following its #includes of the shared blocks) is reduced to the
#define values the emulator needs: the MCP2517FD wiring and CAN bus of boards built on the rp2040_can_block, the
debug UART, the board I2C bus, the flash size, and the remaining *_PIN defines (listed for reference so device
models added later can be wired by name). Sensors and other external devices are added to the generated files by
hand-written overlays in boards/overlays/ (same path), which are appended verbatim.
"""

import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BOARDS_H = os.path.join(ROOT, "external/titan_firmware/lib/titan_boards/include")
CLIENT_IDS_H = os.path.join(ROOT, "external/titan_firmware/lib/titan_canmore/canmore/include/canmore/client_ids.h")
OUT = os.path.join(ROOT, "boards")

DEFINE = re.compile(r"^\s*#\s*define\s+(\w+)(?:\s+(.*?))?\s*(?://.*)?$")
INCLUDE = re.compile(r'^\s*#\s*include\s+"(boards/[^"]+)"')


def read_defines(path, seen=None):
    """#defines of a header and the board headers it includes (later definitions win, #ifndef guards honoured)."""
    seen = seen or set()
    defs = {}
    if path in seen or not os.path.exists(path):
        return defs
    seen.add(path)
    skip = 0
    with open(path) as f:
        for line in f:
            s = line.strip()
            m = re.match(r"#\s*ifndef\s+(\w+)", s)
            if m and m.group(1) in defs:
                skip += 1
                continue
            if s.startswith("#endif") and skip:
                skip -= 1
                continue
            if skip:
                continue
            inc = INCLUDE.match(s)
            if inc:
                defs.update(read_defines(os.path.join(BOARDS_H, inc.group(1)), seen))
                continue
            d = DEFINE.match(s)
            if d:
                defs[d.group(1)] = (d.group(2) or "").strip()
    return defs


def evaluate(expr, defs, depth=0):
    """Integer value of a define (following macro references and simple arithmetic), or None."""
    if depth > 10 or expr is None:
        return None
    expr = expr.strip()
    if expr in defs:
        return evaluate(defs[expr], defs, depth + 1)
    expr = re.sub(r"\b([A-Za-z_]\w*)\b", lambda m: str(evaluate(defs.get(m.group(1)), defs, depth + 1)), expr)
    if not re.fullmatch(r"[0-9xXa-fA-F\s()*+\-/<>]+", expr):
        return None
    try:
        return int(eval(expr, {"__builtins__": {}}))  # numbers and operators only, checked above
    except Exception:
        return None


def client_ids():
    ids = {}
    for name, value in read_defines(CLIENT_IDS_H).items():
        v = evaluate(value, {})
        if v is not None:
            ids[name] = v
    return ids


def board_toml(rel, defs, ids):
    name = rel[:-2]
    lines = [
        f"# Generated by scripts/gen_boards.py from titan_firmware lib/titan_boards/include/boards/{rel}.",
        "# Do not edit: put additions in boards/overlays/ instead.",
        f'name = "{name}"',
        'mcu = "rp2040"',
        "crystal_hz = 12_000_000",
    ]
    flash = evaluate(defs.get("PICO_FLASH_SIZE_BYTES"), defs)
    if flash:
        lines.append(f"flash_size = {flash}")
    bus = defs.get("CAN_BUS_NAME")
    client = None
    for key in ("CAN_BUS_CLIENT_ID", "CAN_BUS_BOARD0_CLIENT_ID", "CAN_BUS_PORT_CLIENT_ID"):
        if key in defs:
            client = ids.get(defs[key], evaluate(defs[key], defs))
            break
    if "MCP2517FD_SPI" in defs and bus:
        lines += [
            "",
            "[can]",
            f'bus = "{"internal" if bus == "INTERNAL_CAN" else "external"}"',
        ]
        if client is not None:
            lines.append(f"client_id = {client}")
        lines += [
            "",
            "[[spi]]",
            f"bus = {evaluate(defs['MCP2517FD_SPI'], defs)}",
            f"cs = {evaluate(defs['MCP2517FD_NCS_PIN'], defs)}",
            "",
            "[spi.mcp2517fd]",
            f"int_pin = {evaluate(defs['MCP2517FD_INT_PIN'], defs)}",
            f"clkin_pin = {evaluate(defs['MCP2517FD_CANCLK_PIN'], defs)}",
            "termination = true",
        ]
    uart_tx = evaluate(defs.get("PICO_DEFAULT_UART_TX_PIN"), defs)
    if uart_tx is not None:
        lines += ["", "[debug_uart]", f"uart = {evaluate(defs.get('PICO_DEFAULT_UART', '0'), defs)}", f"tx_pin = {uart_tx}"]
    i2c = evaluate(defs.get("BOARD_I2C"), defs)
    if i2c is not None:
        lines += [
            "",
            "[i2c_bus]",
            f"i2c = {i2c}",
            f"sda_pin = {evaluate(defs.get('BOARD_SDA_PIN'), defs)}",
            f"scl_pin = {evaluate(defs.get('BOARD_SCL_PIN'), defs)}",
        ]
    pins = {k: evaluate(v, defs) for k, v in sorted(defs.items()) if k.endswith("_PIN") and not k.startswith("PICO_")}
    pins = {k: v for k, v in pins.items() if v is not None}
    if pins:
        lines += ["", "# Pins named in the header", "[pins]"]
        lines += [f"{k.lower()} = {v}" for k, v in pins.items()]
    text = "\n".join(lines) + "\n"
    overlay = os.path.join(OUT, "overlays", name + ".toml")
    if os.path.exists(overlay):
        with open(overlay) as f:
            text += "\n# ---- boards/overlays/" + name + ".toml\n" + f.read()
    return name, text


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    ids = client_ids()
    stale = []
    for dirpath, _, files in os.walk(os.path.join(BOARDS_H, "boards")):
        for fn in sorted(files):
            if not fn.endswith(".h"):
                continue
            rel = os.path.relpath(os.path.join(dirpath, fn), os.path.join(BOARDS_H, "boards"))
            if "/blocks/" in "/" + rel:
                continue
            defs = read_defines(os.path.join(dirpath, fn))
            if "UWRT_BOARD_DEFINED" not in defs and "MCP2517FD_SPI" not in defs:
                continue
            name, text = board_toml(rel, defs, ids)
            path = os.path.join(OUT, name + ".toml")
            old = open(path).read() if os.path.exists(path) else None
            if old != text:
                stale.append(path)
                if not args.check:
                    os.makedirs(os.path.dirname(path), exist_ok=True)
                    with open(path, "w") as f:
                        f.write(text)
    if args.check and stale:
        print("out of date:", *stale, sep="\n  ")
        sys.exit(1)
    if not args.check:
        print(f"{len(stale)} board file(s) written")


if __name__ == "__main__":
    main()
