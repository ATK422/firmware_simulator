//! Generates register tables from `svd/rp2040.svd`:
//! * `PERIPHERALS`: every peripheral with its base address and registers (name, offset, reset value), sorted by
//!   base address, used to name accesses to registers the emulator does not model and to give them their reset
//!   values;
//! * `offsets::<peripheral>::<REGISTER>` constants used by the peripheral models.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

struct Reg {
    name: String,
    offset: u32,
    reset: u32,
}

struct Periph {
    name: String,
    base: u32,
    regs: Vec<Reg>,
}

fn parse_u32(s: &str) -> u32 {
    let s = s.trim();
    if let Some(hex) = s.strip_prefix("0x").or_else(|| s.strip_prefix("0X")) {
        u32::from_str_radix(hex, 16).expect("hex number")
    } else {
        s.parse().expect("number")
    }
}

fn child_text<'a>(node: roxmltree::Node<'a, 'a>, name: &str) -> Option<&'a str> {
    node.children().find(|c| c.has_tag_name(name)).and_then(|c| c.text())
}

fn main() {
    let svd_path = PathBuf::from("svd/rp2040.svd");
    println!("cargo:rerun-if-changed={}", svd_path.display());
    println!("cargo:rerun-if-changed=build.rs");
    let text = std::fs::read_to_string(&svd_path).expect("read SVD");
    let doc = roxmltree::Document::parse(&text).expect("parse SVD");
    let device = doc.root_element();
    let default_reset = child_text(device, "resetValue").map(parse_u32).unwrap_or(0);

    let peripherals_node = device.children().find(|c| c.has_tag_name("peripherals")).expect("peripherals");
    let mut by_name: BTreeMap<String, Vec<(String, u32, u32)>> = BTreeMap::new();
    let mut list: Vec<(String, u32, Option<String>)> = Vec::new();
    for p in peripherals_node.children().filter(|c| c.has_tag_name("peripheral")) {
        let name = child_text(p, "name").expect("peripheral name").to_string();
        let base = parse_u32(child_text(p, "baseAddress").expect("base address"));
        let derived = p.attribute("derivedFrom").map(str::to_string);
        let periph_reset = child_text(p, "resetValue").map(parse_u32).unwrap_or(default_reset);
        let mut regs = Vec::new();
        if let Some(rs) = p.children().find(|c| c.has_tag_name("registers")) {
            for r in rs.children().filter(|c| c.has_tag_name("register")) {
                let rname = child_text(r, "name").expect("register name").to_string();
                let offset = parse_u32(child_text(r, "addressOffset").expect("offset"));
                let reset = child_text(r, "resetValue").map(parse_u32).unwrap_or(periph_reset);
                regs.push((rname, offset, reset));
            }
        }
        by_name.insert(name.clone(), regs);
        list.push((name, base, derived));
    }

    let mut periphs: Vec<Periph> = list
        .into_iter()
        .map(|(name, base, derived)| {
            let src = derived.as_ref().unwrap_or(&name);
            let mut regs: Vec<Reg> =
                by_name[src].iter().map(|(n, o, r)| Reg { name: n.clone(), offset: *o, reset: *r }).collect();
            regs.sort_by_key(|r| r.offset);
            Periph { name, base, regs }
        })
        .collect();
    periphs.sort_by_key(|p| p.base);

    let mut out = String::new();
    out.push_str("// Generated by build.rs from svd/rp2040.svd. Do not edit.\n\n");
    out.push_str("/// Every peripheral of the SVD, sorted by base address.\n");
    out.push_str("pub static PERIPHERALS: &[SvdPeripheral] = &[\n");
    for p in &periphs {
        writeln!(out, "    SvdPeripheral {{ name: {:?}, base: {:#010x}, registers: &[", p.name, p.base).unwrap();
        for r in &p.regs {
            writeln!(
                out,
                "        SvdRegister {{ name: {:?}, offset: {:#x}, reset: {:#010x} }},",
                r.name, r.offset, r.reset
            )
            .unwrap();
        }
        out.push_str("    ] },\n");
    }
    out.push_str("];\n\n");

    out.push_str("/// Register offsets within each peripheral, from the SVD.\n");
    out.push_str("#[allow(dead_code)]\npub mod offsets {\n");
    let mut seen_mods = std::collections::BTreeSet::new();
    for p in &periphs {
        let module = p.name.to_lowercase();
        if !seen_mods.insert(module.clone()) {
            continue;
        }
        writeln!(out, "    pub mod {module} {{").unwrap();
        let mut seen = std::collections::BTreeSet::new();
        for r in &p.regs {
            if seen.insert(r.name.clone()) {
                writeln!(out, "        pub const {}: u32 = {:#x};", r.name, r.offset).unwrap();
            }
        }
        out.push_str("    }\n");
    }
    out.push_str("}\n");

    let out_path = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("svd_gen.rs");
    std::fs::write(out_path, out).expect("write generated file");
}
